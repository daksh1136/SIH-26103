    for idx in range(total_m):
        title, weight, target_date = stages[idx % len(stages)]
        
        # Determine status
        if idx < int((phys / 100) * total_m):
            m_status = "COMPLETED"
            m_delay = 0
            m_prog = 100
        elif idx == int((phys / 100) * total_m) and delayed_count > 0:
            m_status = "DELAYED" if p["status"] != "CRITICAL" else "CRITICAL"
            m_delay = 45 if p["status"] != "CRITICAL" else 95
            m_prog = int((phys % (100 / total_m)) * (total_m / 100) * 100)
        elif idx < int((phys / 100) * total_m) + delayed_count:
            m_status = "DELAYED"
            m_delay = 30
            m_prog = 20
        else:
            m_status = "SCHEDULED"
            m_delay = 0
            m_prog = 0
            
        MILESTONES.append({
            "id": m_id,
            "project_id": p["id"],
            "title": f"M{idx+1}: {title}",
            "weightage_pct": weight,
            "target_date": target_date,
            "progress_pct": m_prog,
            "delay_days": m_delay,
            "status": m_status,
            "is_critical_path": idx in (1, 2, 3)
        })
        m_id += 1

